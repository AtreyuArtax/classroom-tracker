export function resolveHistoryStrand(topicOrCode = '') {
  const s = String(topicOrCode || '').toLowerCase().trim()
  if (s.includes('changing') || s.includes('1890') || s.includes('1914') || s.includes('immigrat') || s.startsWith('b')) {
    return GRADE_8_HISTORY_STRANDS.STRAND_B
  }
  return GRADE_8_HISTORY_STRANDS.STRAND_A
}
